--  Жалоба: «плашки над НПС/энтити не видны спереди — видно
--  только если смотреть за спину (и то сзади)».
--  ДВЕ ПРИЧИНЫ:
--   1) плашка рисуется В ТОЧКЕ МОДЕЛИ (pos + Vector(0,0,84) —
--      на уровне головы/корпуса) и с передней стороны её
--      ПЕРЕКРЫВАЕТ геометрия самого НПС/энтити (глубина);
--   2) угол 3D2D иногда смотрит в сторону, а не на игрока.
--  РЕШЕНИЕ (без правки 20 файлов): оборачиваем cam.Start3D2D/
--  cam.End3D2D — вокруг каждого 3D2D-блока включаем
--  cam.IgnoreZ(true) (текст рисуется СКВОЗЬ геометрию, всегда
--  поверх) и после — выключаем. Угол не трогаем (3D2D в GMod
--  двусторонний) — плашка теперь видна и спереди, и сзади.
--  Старые файлы не трогаем. ДОСТАВКА: cl_init энтити ВСЕГДА.
-- ============================================================

local OrigStart3D2D = cam.Start3D2D
local OrigEnd3D2D   = cam.End3D2D

local function Patch3D2D()
    if cam.P11_PlatesPatched then return end

    cam.Start3D2D = function(pos, ang, scale)
        cam.IgnoreZ(true) -- плашка поверх геометрии (не прячется за моделью)
        OrigStart3D2D(pos, ang, scale)
    end

    cam.End3D2D = function()
        OrigEnd3D2D()
        cam.IgnoreZ(false)
    end

    cam.P11_PlatesPatched = true
    print("[POLUS-11] v5.8.22: 3D2D-плашки рисуются сквозь геометрию — видны спереди и сзади")
end

Patch3D2D()
timer.Simple(1, Patch3D2D)
timer.Simple(3, Patch3D2D)
timer.Simple(6, Patch3D2D)
