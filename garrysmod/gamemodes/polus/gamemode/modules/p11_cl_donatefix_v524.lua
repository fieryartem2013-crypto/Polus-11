-- ============================================================
--  ПОЛЮС-11 — ФИКС ДОНАТ-МЕНЮ F6 (client) v5.2.4 (НОВЫЙ ФАЙЛ)
--  Баг «много кликов при открытии F6»: хук P11.DonateF6 создаёт
--  окно (OpenDonate), но это же окно в OnKeyCodePressed закрывает
--  себя по KEY_F6 — нажатие, которым окно открылось, тут же его
--  и закрывает. В итоге меню мигает, и приходится жать F6 много раз.
--  (Батл-пасс F5 такую проблему не имеет: там закрытие только по ESC.)
--
--  Решение БЕЗ правки старого файла: наш хук срабатывает ПОСЛЕ
--  P11.DonateF6 (зарегистрирован позже) и сразу подменяет
--  OnKeyCodePressed окна на «закрытие только по ESC». Открытие/
--  закрытие по F6 остаётся на оригинальном хуке (работает).
-- ============================================================

hook.Add("PlayerButtonDown", "P11.DonateFixF6", function(ply, btn)
    if btn ~= KEY_F6 or ply ~= LocalPlayer() then return end
    local f = P11D and P11D.Frame
    if IsValid(f) then
        -- v5.2.4: окно только что открылось хуком P11.DonateF6 —
        -- убираем закрытие по F6 (оставляем ESC), иначе меню мигает
        f.OnKeyCodePressed = function(s, key)
            if key == KEY_ESCAPE then s:Remove() end
        end
    end
end)

print("[POLUS-11] фикс F6 v5.2.4: донат-меню больше не закрывается тем же нажатием (только ESC)")
