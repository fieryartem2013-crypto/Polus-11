local function ToggleHelp()
    if IsValid(POLUS11.HelpFrame) then POLUS11.HelpFrame:Remove() return end
    local C = P11UI and P11UI.C or {}

    local f = P11UI and P11UI.Frame("СТАНЦИЯ «ПОЛЮС-11» — ПАМЯТКА ЭКИПАЖА",
        "F1 — закрыть · справка обновлена под сборку v4.1", 660, 580)
        or vgui.Create("DFrame")
    POLUS11.HelpFrame = f

    local scroll = P11UI.Scroll(f, 12, 64, 636, 504)

    local function H(t) P11UI.Head(scroll, t) end
    local function B(t) P11UI.Body(scroll, t, 600) end

    H("ЧТО ЭТО ЗА РЕЖИМ?")
    B("Станция «Полюс-11», Антарктида, 1982. Гарнизон, НКВД, учёные и персонал — против НЕЧТО: существа, которое съедает человека и идеально копирует его — лицо, голос, имя в чате. Кто-то из присутствующих уже может быть не тем, за кого себя выдаёт. Доверяй только огню и тесту крови.")

    H("С ЧЕГО НАЧАТЬ?")
    B("1) Подойди к NPC-кадровику (смотрит на тебя, поворачивает голову) — E или F4, возьми должность. 2) Делай задачи смены (список слева). 3) Держи генератор живым: солярка, износ, поломки. 4) ДЕЛАЙ СВОЁ ДЕЛО — у каждой должности теперь личные занятия за рубли (см. ниже).")

    H("СМЕННЫЕ ДЕЛА И МИНИИГРЫ (v4.1)", C.science)
    B("Почти у каждой должности появились свои занятия с минииграми «нажми клавишу вовремя» (следи за буквой [R/F/T/G] и сжимающимся кольцом):\n• УЧЁНЫЙ — калибровка анализатора: E по лабораторному столу без колбы (60₽ + очки науки).\n• ТЕХНИК — ТО генератора миниигрой при износе 35+/поломке (100₽, снятие нагара).\n• УБОРЩИК — мешки грязи по станции: E, два шага (35₽).\n• БОЕЦ РККА — патруль: обходи посты, E + 3 сек досмотра (25₽ за пост, 150₽ за полный круг).")

    H("ОЧКИ НАУКИ (RP) И ГРАНТ ЦНИИ (v4.1)")
    B("Забор крови (+1 RP), тест (+2), вскрытие (+3), калибровка (+1) — копятся в счётчике 🔬 слева внизу. Каждые 5 RP — автоматический ГРАНТ ЦНИИ: 250₽ и слава в общий чат. Наука на Полюсе теперь кормит.")

    H("ПАТРУЛЬ РККА (v4.1)", C.patrol)
    B("Посты патруля (столбы с синими кольцами) ставит администрация. Подойди к посту с винтовкой, жми E и стой 3 секунды. Следующий пост подсвечивается маркером 🚩 с дистанцией. Полный обход — премия 150₽ и запись в журнал гарнизона. Задача «Обойди посты патруля» в списке смены.")

    H("РУБЛИ, БАГАЖ И ЛАРЁК (v4.0)")
    B("2000₽ за все задачи смены, 500₽ за доп-задачу терминала, мелкие выплаты за дела. /деньги — баланс. У ЛАРЬКА СНАБЖЕНИЯ (E) — оружие ARC9/EFT, рации, пайки, шприцы. Покупки живут в 🎒 БАГАЖЕ (C-меню), переживают смерть; излишки — в ЛИЧНЫЙ СЕЙФ.")

    H("КТО ЗДЕСЬ КТО? (v3.8–3.9)")
    B("РККА — посты, патрули, генералы с !приказ. НКВД — допросы, надзор за тестами, ОСОБИСТ с !розыск. УЧЁНЫЕ — образцы, тесты, вскрытия и теперь гранты. ПЕРСОНАЛ: ГРУЗЧИК — бочки, ТЕХНИК — генераторы, МЕДИК — ПКМ шприца, ПОВАР — кормит, УБОРЩИК — чистит и слышит всё, ИНЖЕНЕР — огнемёт.")

    H("ГЕНЕРАТОР, ХОЛОД И МОРОЗ")
    B("Генератор изнашивается и ломается (перегрев/утечка/стартер/скачки): обычные люди — держат E, техник — играет ТО. CTRL+E — режим РЕЗЕРВ. На морозе теряешь тепло: 2,5 минуты льготы после спавна, дальше грейся у генераторов, в помещениях, горячим пайком.")

    H("ОСОБАЯ ВАКАНСИЯ")
    B("Кадровик иногда вывешивает красную «особую вакансию». Первый нажавший E — тихо становится НОСИТЕЛЕМ. Никто не знает, кто это взял. Так Нечто приходит на станцию.")

    H("ДОКУМЕНТЫ")
    B("Удостоверение с личным кодом на всю смену: ЛКМ — предъявить, ПКМ/R — свои. Нечто под маской покажет украденное имя.")

    H("КЛАВИШИ")
    B("F1 — справка • F4 — должности • F2 — 3-е лицо • F3 — свободный курсор • TAB — состав станции • C — действия/жесты/багаж • Q — строительство • /р — рация • !работа • !репорт — админам • !ролл • /menu — панель админов.")

    H("ЕСЛИ ТЫ НЕЧТО...")
    B("Не показывайся. Воруй личности, действуй в темноте. R — маскировка, !крик — устрашение, !форма — смена тела. Тест крови и вскрытие тебя выдают.")

    H("ПРАВИЛА СТАНЦИИ")
    B("Не мешай RP. Не палюй стройку. Арест/бан — за дело. Вопросы — администрации (звание в TAB). Сборка готовится к ОТКРЫТОМУ АЛЬФА-ТЕСТУ: нашёл баг — !репорт.")
end

concommand.Add("p11_help", ToggleHelp)

hook.Add("PlayerBindPress", "P11.HelpF1", function(ply, bind, pressed)
    if not pressed then return end
    if bind == "gm_showhelp" then
        ToggleHelp()
        return true
    end
end)
