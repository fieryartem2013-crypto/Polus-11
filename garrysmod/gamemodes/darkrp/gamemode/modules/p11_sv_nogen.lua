--  ПОЛЮС-11 — ЭНЕРГОСИСТЕМА ВЫВЕДЕНА ИЗ ИГРЫ v4.12.0 «ОТБОЙ»
--  Заявка владельца: «вырежи из игры наглухо генераторы».
--  Энтити polus11_generator больше НЕ существует в геймплее:
--  любая попытка поставить её (persist-файлы эпохи v3.x, Q-меню,
--  📍 расстановка, админ-спавн) снимается в ноль. Свет на станции
--  горит всегда; тьма приходит только по воле Нечто (пульт/фазы).
--  Задачи «долей солярку/отремонтируй генератор» заменены новыми
--  делами смены (лут-обыск и верстак-крафт) — p11_sv_tasks.lua.
-- ============================================================

hook.Add("OnEntityCreated", "P11.NoGenerator", function(e)
    if not IsValid(e) or e:GetClass() ~= "polus11_generator" then return end
    timer.Simple(0, function()
        if IsValid(e) then
            e:Remove()
            if POLUS11 and POLUS11.Log then
                POLUS11.Log("ОТБОЙ: попытка поставить генератор — снята (v4.12.0)")
            end
        end
    end)
end)

print("[POLUS-11] энергосистема ВЫВЕДЕНА из игры v4.12.0 «ОТБОЙ»: генераторов нет и не будет; дела механика — верстак и лут")
